CREATE EXTENSION IF NOT EXISTS btree_gist WITH SCHEMA public;
CREATE EXTENSION IF NOT EXISTS pgcrypto WITH SCHEMA public;
CREATE SCHEMA beauty;
REVOKE ALL ON SCHEMA beauty FROM PUBLIC;
CREATE FUNCTION beauty.local_now() RETURNS timestamp LANGUAGE sql VOLATILE
SET search_path = pg_catalog AS $$ SELECT clock_timestamp() AT TIME ZONE 'Europe/Moscow' $$;

CREATE TABLE beauty.user_account (
 user_id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 email text NOT NULL CHECK (email = lower(btrim(email)) AND email LIKE '%@%'),
 password_hash text,
 display_name text NOT NULL CHECK (btrim(display_name) <> ''),
 role text NOT NULL CHECK (role IN ('CLIENT','MASTER','OWNER','ADMIN')),
 account_status text NOT NULL DEFAULT 'ACTIVE' CHECK (account_status IN ('INVITED','ACTIVE','BLOCKED','ARCHIVED')),
 created_at timestamp NOT NULL DEFAULT beauty.local_now(),
 CONSTRAINT uq_user_email UNIQUE(email),
 CONSTRAINT ck_invited_role CHECK(account_status<>'INVITED' OR role='MASTER'),
 CONSTRAINT ck_password CHECK (password_hash IS NOT NULL OR (role='MASTER' AND account_status='INVITED'))
);
CREATE TABLE beauty.district (
 district_id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 name text NOT NULL UNIQUE CHECK(btrim(name)<>''), is_active boolean NOT NULL DEFAULT true
);
CREATE TABLE beauty.salon (
 salon_id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 owner_user_id bigint NOT NULL UNIQUE REFERENCES beauty.user_account ON DELETE RESTRICT,
 district_id bigint NOT NULL REFERENCES beauty.district ON DELETE RESTRICT,
 name text NOT NULL CHECK(btrim(name)<>''), description text NOT NULL DEFAULT '',
 address text NOT NULL CHECK(btrim(address)<>''),
 latitude numeric(9,6) NOT NULL CHECK(latitude BETWEEN -90 AND 90),
 longitude numeric(9,6) NOT NULL CHECK(longitude BETWEEN -180 AND 180),
 phone text NOT NULL, opening_hours text NOT NULL,
 publication_status text NOT NULL DEFAULT 'PENDING'
   CHECK(publication_status IN ('PENDING','RETURNED','PUBLISHED','UNPUBLISHED','BLOCKED','ARCHIVED')),
 created_at timestamp NOT NULL DEFAULT beauty.local_now()
);
CREATE TABLE beauty.service_type (
 service_type_id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 name text NOT NULL UNIQUE CHECK(btrim(name)<>''), description text NOT NULL DEFAULT '',
 is_active boolean NOT NULL DEFAULT true
);
CREATE TABLE beauty.salon_service (
 salon_service_id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 salon_id bigint NOT NULL REFERENCES beauty.salon ON DELETE RESTRICT,
 service_type_id bigint NOT NULL REFERENCES beauty.service_type ON DELETE RESTRICT,
 name text NOT NULL CHECK(btrim(name)<>''), description text NOT NULL DEFAULT '',
 price numeric(12,2) NOT NULL CHECK(price>=0),
 duration_minutes integer NOT NULL CHECK(duration_minutes>0),
 is_active boolean NOT NULL DEFAULT true
);
CREATE TABLE beauty.master (
 master_id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 user_id bigint NOT NULL UNIQUE REFERENCES beauty.user_account ON DELETE RESTRICT,
 salon_id bigint NOT NULL REFERENCES beauty.salon ON DELETE RESTRICT,
 specialization text NOT NULL DEFAULT '', experience_description text NOT NULL DEFAULT '',
 is_active boolean NOT NULL DEFAULT true
);
CREATE TABLE beauty.master_service (
 master_id bigint NOT NULL REFERENCES beauty.master ON DELETE RESTRICT,
 salon_service_id bigint NOT NULL REFERENCES beauty.salon_service ON DELETE RESTRICT,
 is_active boolean NOT NULL DEFAULT true,
 PRIMARY KEY(master_id,salon_service_id)
);
CREATE TABLE beauty.work_interval (
 work_interval_id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 master_id bigint NOT NULL REFERENCES beauty.master ON DELETE RESTRICT,
 work_date date NOT NULL, start_time time NOT NULL, end_time time NOT NULL,
 slot tsrange GENERATED ALWAYS AS (tsrange(work_date+start_time,work_date+end_time,'[)')) STORED,
 CHECK(start_time<end_time),
 CONSTRAINT ex_work_overlap EXCLUDE USING gist(master_id WITH =, slot WITH &&)
);
CREATE TABLE beauty.appointment (
 appointment_id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 client_user_id bigint NOT NULL REFERENCES beauty.user_account ON DELETE RESTRICT,
 master_id bigint NOT NULL, salon_service_id bigint NOT NULL,
 start_at timestamp NOT NULL,
 service_name_snapshot text NOT NULL,
 price_snapshot numeric(12,2) NOT NULL CHECK(price_snapshot>=0),
 duration_snapshot integer NOT NULL CHECK(duration_snapshot>0),
 end_at timestamp GENERATED ALWAYS AS (start_at+make_interval(mins=>duration_snapshot)) STORED,
 slot tsrange GENERATED ALWAYS AS (tsrange(start_at,start_at+make_interval(mins=>duration_snapshot),'[)')) STORED,
 status text NOT NULL DEFAULT 'CONFIRMED' CHECK(status IN ('CONFIRMED','CANCELLED','COMPLETED','NO_SHOW')),
 created_at timestamp NOT NULL DEFAULT beauty.local_now(),
 cancelled_at timestamp, cancelled_by_user_id bigint REFERENCES beauty.user_account ON DELETE RESTRICT,
 cancellation_reason text,
 result_marked_at timestamp, result_marked_by_user_id bigint REFERENCES beauty.user_account ON DELETE RESTRICT,
 FOREIGN KEY(master_id,salon_service_id) REFERENCES beauty.master_service ON DELETE RESTRICT,
 CONSTRAINT ck_start_grid CHECK(extract(minute FROM start_at)::integer % 15=0 AND extract(second FROM start_at)=0),
 CONSTRAINT ck_appointment_evidence CHECK (
  (status='CONFIRMED' AND cancelled_at IS NULL AND cancelled_by_user_id IS NULL AND cancellation_reason IS NULL
    AND result_marked_at IS NULL AND result_marked_by_user_id IS NULL) OR
  (status='CANCELLED' AND cancelled_at IS NOT NULL AND cancelled_by_user_id IS NOT NULL
    AND result_marked_at IS NULL AND result_marked_by_user_id IS NULL) OR
  (status IN ('COMPLETED','NO_SHOW') AND result_marked_at IS NOT NULL AND result_marked_by_user_id IS NOT NULL
    AND cancelled_at IS NULL AND cancelled_by_user_id IS NULL AND cancellation_reason IS NULL)
 ),
 CONSTRAINT ex_appointment_overlap EXCLUDE USING gist(master_id WITH =, slot WITH &&) WHERE(status<>'CANCELLED')
);
-- These two relations represent elements of compound multivalued attributes.
CREATE TABLE beauty.salon_photo (
 salon_id bigint NOT NULL REFERENCES beauty.salon ON DELETE RESTRICT,
 file_path text NOT NULL CHECK(btrim(file_path)<>''), caption text NOT NULL DEFAULT '',
 sort_order integer NOT NULL DEFAULT 0 CHECK(sort_order>=0),
 visibility text NOT NULL DEFAULT 'PUBLISHED' CHECK(visibility IN ('PUBLISHED','HIDDEN','ARCHIVED')),
 mime_type text NOT NULL CHECK(mime_type IN ('image/jpeg','image/png')),
 byte_size integer NOT NULL CHECK(byte_size BETWEEN 1 AND 5242880),
 created_at timestamp NOT NULL DEFAULT beauty.local_now(), PRIMARY KEY(salon_id,file_path)
);
CREATE TABLE beauty.master_photo (
 master_id bigint NOT NULL REFERENCES beauty.master ON DELETE RESTRICT,
 file_path text NOT NULL CHECK(btrim(file_path)<>''), caption text NOT NULL DEFAULT '',
 sort_order integer NOT NULL DEFAULT 0 CHECK(sort_order>=0),
 visibility text NOT NULL DEFAULT 'PUBLISHED' CHECK(visibility IN ('PUBLISHED','HIDDEN','ARCHIVED')),
 mime_type text NOT NULL CHECK(mime_type IN ('image/jpeg','image/png')),
 byte_size integer NOT NULL CHECK(byte_size BETWEEN 1 AND 5242880),
 created_at timestamp NOT NULL DEFAULT beauty.local_now(), PRIMARY KEY(master_id,file_path)
);
CREATE TABLE beauty.review (
 review_id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 appointment_id bigint NOT NULL REFERENCES beauty.appointment ON DELETE RESTRICT,
 target_type text NOT NULL CHECK(target_type IN ('SALON','MASTER')),
 rating smallint NOT NULL CHECK(rating BETWEEN 1 AND 5), text text,
 visibility text NOT NULL DEFAULT 'PUBLISHED' CHECK(visibility IN ('PUBLISHED','HIDDEN')),
 created_at timestamp NOT NULL DEFAULT beauty.local_now(),
 UNIQUE(appointment_id,target_type)
);
CREATE TABLE beauty.moderation_decision (
 decision_id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 admin_user_id bigint NOT NULL REFERENCES beauty.user_account ON DELETE RESTRICT,
 target_user_id bigint REFERENCES beauty.user_account ON DELETE RESTRICT,
 target_salon_id bigint REFERENCES beauty.salon ON DELETE RESTRICT,
 target_master_id bigint REFERENCES beauty.master ON DELETE RESTRICT,
 target_review_id bigint REFERENCES beauty.review ON DELETE RESTRICT,
 photo_path text,
 action text NOT NULL CHECK(action IN ('APPROVE','RETURN','PUBLISH','UNPUBLISH','BLOCK','UNBLOCK','HIDE','RESTORE')),
 reason text NOT NULL CHECK(btrim(reason)<>''), created_at timestamp NOT NULL DEFAULT beauty.local_now(),
 CHECK(num_nonnulls(target_user_id,target_salon_id,target_master_id,target_review_id)=1),
 CHECK(photo_path IS NULL OR (btrim(photo_path)<>'' AND num_nonnulls(target_salon_id,target_master_id)=1)),
 FOREIGN KEY(target_salon_id,photo_path) REFERENCES beauty.salon_photo(salon_id,file_path) ON DELETE RESTRICT,
 FOREIGN KEY(target_master_id,photo_path) REFERENCES beauty.master_photo(master_id,file_path) ON DELETE RESTRICT
);
CREATE TABLE beauty.master_invitation (
 invitation_id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 master_id bigint NOT NULL REFERENCES beauty.master ON DELETE RESTRICT,
 created_by_user_id bigint NOT NULL REFERENCES beauty.user_account ON DELETE RESTRICT,
 token_hash text NOT NULL UNIQUE,
 created_at timestamp NOT NULL DEFAULT beauty.local_now(), expires_at timestamp NOT NULL,
 used_at timestamp, revoked_at timestamp,
 CHECK(expires_at>created_at), CHECK(num_nonnulls(used_at,revoked_at)<=1),
 CHECK(used_at IS NULL OR (used_at>=created_at AND used_at<expires_at)),
 CHECK(revoked_at IS NULL OR revoked_at>=created_at)
);
COMMENT ON TABLE beauty.salon_photo IS 'Элементы многозначного атрибута салона: фотографии интерьера';
COMMENT ON TABLE beauty.master_photo IS 'Элементы многозначного атрибута мастера: фотографии работ';
COMMENT ON TABLE beauty.master_invitation IS 'Техническая реализация одноразового приглашения из П1 и П8';
